export function exactSearchConcept(value: string) {
  const key = normalizeSearchTerm(value);
  return SEARCH_CONCEPTS.find((c) =>
    [c.id, c.label, ...c.aliases].some((a) => normalizeSearchTerm(a) === key),
  );
}
