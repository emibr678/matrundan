import type { FoodTagGroup } from "./food-tags";
import type { PlaceCategory } from "./types";

export interface SearchConcept {
  id: string;
  label: string;
  group: FoodTagGroup;
  groupLabel: "Typ" | "Kök" | "Inriktning";
  kind: "category" | "food-tag";
  category?: PlaceCategory;
  surface: "main" | "extra";
  aliases: string[];
  tokens: string[];
  family?: boolean;
  profile?: "vegetarian" | "vegan";
}
export function normalizeSearchTerm(s: string): string {
  return s
    .trim()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase("sv-SE")
    .replace(/[–—_-]+/g, " ")
    .replace(/\s+/g, " ");
}

